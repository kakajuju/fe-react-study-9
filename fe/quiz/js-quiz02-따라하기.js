// 1) i가 0~10으로 11번 반복
let i;

for (i = 0; i < 11; i++) {
    console.log(i);
}
// 2) i가 1~9로 9번 반복
console.log('---------------------------');
for (i = 1; i <= 9; i++) {
    console.log(i);
}
// 3) i가 10 ~ 100 으로 10번 반복
console.log('---------------------------');
for (i = 10; i <= 100; i += 10) {
    console.log(i);
}
// 4) i가 25 50 75 100 해서 4번 반복
console.log('---------------------------');
for (i = 15; i <= 100; i += 25) {
    console.log(i);
}
for (i = 1; i <= 4; i ++) {
    console.log(i*25);
}
// 5) i가 50 ~ 55로 6번 반복
console.log('---------------------------');
